-- (b) FUNCTION: fn_daily_load
-- Counts non-cancelled appointments for one doctor on one day.

CREATE OR REPLACE FUNCTION fn_daily_load(
    p_doctor_id INTEGER,
    p_day DATE
)
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_count INTEGER;
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM doctors
        WHERE doctor_id = p_doctor_id
    ) THEN
        RAISE EXCEPTION 'Doctor ID % does not exist', p_doctor_id;
    END IF;

    SELECT COUNT(*)::INTEGER
    INTO v_count
    FROM appointments
    WHERE doctor_id = p_doctor_id
      AND appointment_day = p_day
      AND status <> 'CANCELLED';

    RETURN COALESCE(v_count, 0);
END;
$$;


-- (d) TRIGGER: prevent appointment clashes
-- A clash occurs when the same doctor, date and slot are
-- already occupied by another non-cancelled appointment.

CREATE OR REPLACE FUNCTION fn_check_appointment_clash()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.status <> 'CANCELLED' THEN

        IF EXISTS (
            SELECT 1
            FROM appointments a
            WHERE a.doctor_id = NEW.doctor_id
              AND a.appointment_day = NEW.appointment_day
              AND a.slot_time = NEW.slot_time
              AND a.status <> 'CANCELLED'
              AND a.appointment_id <> COALESCE(NEW.appointment_id, -1)
        ) THEN
            RAISE EXCEPTION
                'Appointment clash: this doctor already has a non-cancelled appointment at that date and time';
        END IF;

    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_check_appointment_clash
BEFORE INSERT OR UPDATE ON appointments
FOR EACH ROW
EXECUTE FUNCTION fn_check_appointment_clash();


-- (c) PROCEDURE: pr_book_appointment
-- Validates patient, doctor, date and slot before booking.

CREATE OR REPLACE PROCEDURE pr_book_appointment(
    p_patient_id INTEGER,
    p_doctor_id INTEGER,
    p_day DATE,
    p_slot TIME
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM patients
        WHERE patient_id = p_patient_id
    ) THEN
        RAISE EXCEPTION 'Patient ID % does not exist', p_patient_id;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM doctors
        WHERE doctor_id = p_doctor_id
    ) THEN
        RAISE EXCEPTION 'Doctor ID % does not exist', p_doctor_id;
    END IF;

    IF p_day IS NULL OR p_day < CURRENT_DATE THEN
        RAISE EXCEPTION 'Appointment date cannot be in the past';
    END IF;

    IF p_slot IS NULL OR p_slot NOT IN (
        TIME '09:00',
        TIME '10:00',
        TIME '11:00',
        TIME '12:00'
    ) THEN
        RAISE EXCEPTION 'Unsupported appointment slot';
    END IF;

    INSERT INTO appointments (
        patient_id,
        doctor_id,
        appointment_day,
        slot_time,
        status
    )
    VALUES (
        p_patient_id,
        p_doctor_id,
        p_day,
        p_slot,
        'BOOKED'
    );
END;
$$;


