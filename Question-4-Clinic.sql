-- (g) PROCEDURE: refresh daily clinic summary
-- Counts BOOKED, ATTENDED and CANCELLED appointments separately.
-- Re-running the procedure replaces the existing date's summary.

CREATE OR REPLACE PROCEDURE pr_refresh_clinic_summary(
    p_day DATE
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_booked INTEGER;
    v_attended INTEGER;
    v_cancelled INTEGER;
BEGIN
    SELECT
        COUNT(*) FILTER (WHERE status = 'BOOKED')::INTEGER,
        COUNT(*) FILTER (WHERE status = 'ATTENDED')::INTEGER,
        COUNT(*) FILTER (WHERE status = 'CANCELLED')::INTEGER
    INTO
        v_booked,
        v_attended,
        v_cancelled
    FROM appointments
    WHERE appointment_day = p_day;

    INSERT INTO clinic_summary (
        summary_date,
        booked_count,
        attended_count,
        cancelled_count
    )
    VALUES (
        p_day,
        v_booked,
        v_attended,
        v_cancelled
    )
    ON CONFLICT (summary_date)
    DO UPDATE SET
        booked_count = EXCLUDED.booked_count,
        attended_count = EXCLUDED.attended_count,
        cancelled_count = EXCLUDED.cancelled_count;
END;
$$;


